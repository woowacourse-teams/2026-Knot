"""PostgreSQL/pgvector storage and cosine retrieval for the benchmark."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Final

import psycopg
from benchmark_core import Chunk, tokenize
from pgvector.psycopg import register_vector

_TABLE_NAME = "benchmark_rag_chunks"
_TERM_ALIASES: Final[dict[str, tuple[str, ...]]] = {
    "database": ("database", "db", "데이터베이스"),
    "notion": ("notion", "노션"),
}


class PgVectorStoreError(Exception):
    """Raised when the isolated benchmark store cannot satisfy an operation."""

    __slots__ = ("reason",)

    reason: str

    def __init__(self, reason: str) -> None:
        super().__init__(reason)
        self.reason = reason

    def __str__(self) -> str:
        return f"pgvector store error: {self.reason}"


@dataclass(frozen=True, slots=True)
class StoredChunk:
    """A chunk plus its persisted vector-search score."""

    source_path: str
    title: str
    content: str
    score: float


class PgVectorStore:
    """Small isolated pgvector store for one benchmark corpus."""

    def __init__(self, database_url: str) -> None:
        self._connection = psycopg.connect(database_url)
        self._dimensions: int | None = None

    def close(self) -> None:
        """Close the PostgreSQL connection."""
        self._connection.close()

    def reset_schema(self, dimensions: int) -> None:
        """Create the extension, table, and HNSW cosine index for a run."""
        if dimensions < 1:
            raise PgVectorStoreError("vector dimensions must be positive")
        with self._connection.cursor() as cursor:
            cursor.execute("CREATE EXTENSION IF NOT EXISTS vector")
            cursor.execute(f"DROP TABLE IF EXISTS {_TABLE_NAME}")
            cursor.execute(
                f"""
                CREATE TABLE {_TABLE_NAME} (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    corpus_key TEXT NOT NULL,
                    source_path TEXT NOT NULL,
                    title TEXT NOT NULL,
                    chunk_index INTEGER NOT NULL,
                    content TEXT NOT NULL,
                    search_text TEXT GENERATED ALWAYS AS (
                        lower(title || ' ' || source_path || ' ' || content)
                    ) STORED,
                    embedding vector({dimensions}) NOT NULL,
                    UNIQUE (corpus_key, source_path, chunk_index)
                )
                """
            )
            cursor.execute("CREATE EXTENSION IF NOT EXISTS pg_trgm")
            cursor.execute(
                f"""
                CREATE INDEX {_TABLE_NAME}_embedding_hnsw
                ON {_TABLE_NAME}
                USING hnsw ((embedding::halfvec({dimensions})) halfvec_cosine_ops)
                """
            )
            cursor.execute(
                f"CREATE INDEX {_TABLE_NAME}_corpus_path ON {_TABLE_NAME} (corpus_key, source_path)"
            )
            cursor.execute(
                f"CREATE INDEX {_TABLE_NAME}_search_text_trgm ON {_TABLE_NAME} USING gin (search_text gin_trgm_ops)"
            )
        self._connection.commit()
        register_vector(self._connection)
        self._dimensions = dimensions

    def replace_chunks(
        self,
        corpus_key: str,
        chunks: tuple[Chunk, ...],
        vectors: tuple[tuple[float, ...], ...],
    ) -> None:
        """Replace one corpus atomically with its embedded chunks."""
        if len(chunks) != len(vectors):
            raise PgVectorStoreError("chunk and vector counts must match")
        with self._connection.cursor() as cursor:
            cursor.execute(f"DELETE FROM {_TABLE_NAME} WHERE corpus_key = %s", (corpus_key,))
            cursor.executemany(
                f"""
                INSERT INTO {_TABLE_NAME}
                    (corpus_key, source_path, title, chunk_index, content, embedding)
                VALUES (%s, %s, %s, %s, %s, %s)
                """,
                (
                    (corpus_key, str(chunk.path), chunk.title, index, chunk.content, list(vector))
                    for index, (chunk, vector) in enumerate(zip(chunks, vectors, strict=True))
                ),
            )
        self._connection.commit()

    def search(
        self,
        corpus_key: str,
        query_vector: tuple[float, ...],
        top_k: int,
        *,
        distinct_sources: bool = True,
    ) -> tuple[StoredChunk, ...]:
        """Return vector passages, optionally collapsed to distinct sources."""
        if top_k < 1:
            return ()
        dimensions = self._dimensions or self._load_dimensions()
        candidate_limit = max(top_k * 8, top_k)
        with self._connection.cursor() as cursor:
            cursor.execute(
                f"""
                SELECT source_path, title, content,
                    1 - (embedding::halfvec({dimensions}) <=> %s::halfvec) AS score
                FROM {_TABLE_NAME}
                WHERE corpus_key = %s
                ORDER BY embedding::halfvec({dimensions}) <=> %s::halfvec
                LIMIT %s
                """,
                (list(query_vector), corpus_key, list(query_vector), candidate_limit),
            )
            rows = cursor.fetchall()
        if distinct_sources:
            return self._distinct_rows(rows, top_k)
        return self._stored_rows(rows, top_k)

    def search_keyword(
        self,
        corpus_key: str,
        query: str,
        top_k: int,
        *,
        distinct_sources: bool = True,
    ) -> tuple[StoredChunk, ...]:
        """Return lexical passages, optionally collapsed to distinct sources."""
        if top_k < 1:
            return ()
        terms = _expanded_terms(query)
        if not terms:
            return ()
        patterns = tuple(f"%{term}%" for term in terms)
        content_score_sql = " + ".join(
            f"{_term_weight(term)} * CASE WHEN lower(content) LIKE %s THEN 1 ELSE 0 END" for term in terms
        )
        score_sql = " + ".join(
            f"{_term_weight(term)} * CASE WHEN search_text LIKE %s THEN 1 ELSE 0 END" for term in terms
        )
        where_sql = " OR ".join("search_text LIKE %s" for _ in terms)
        candidate_limit = max(top_k * 8, top_k)
        with self._connection.cursor() as cursor:
            cursor.execute(
                f"""
                SELECT source_path, title, content,
                    ({content_score_sql}) AS content_score,
                    ({score_sql}) AS score
                FROM {_TABLE_NAME}
                WHERE corpus_key = %s AND ({where_sql})
                ORDER BY content_score DESC, score DESC, source_path, chunk_index
                LIMIT %s
                """,
                (*patterns, *patterns, corpus_key, *patterns, candidate_limit),
            )
            rows = cursor.fetchall()
        if distinct_sources:
            return self._distinct_keyword_rows(rows, top_k)
        return self._keyword_rows(rows, top_k)

    def _load_dimensions(self) -> int:
        with self._connection.cursor() as cursor:
            cursor.execute(f"SELECT vector_dims(embedding) FROM {_TABLE_NAME} LIMIT 1")
            row = cursor.fetchone()
        if row is None:
            raise PgVectorStoreError("pgvector corpus has no stored vectors")
        self._dimensions = int(row[0])
        return self._dimensions

    def count(self, corpus_key: str) -> int:
        """Return the number of stored chunks for a corpus."""
        with self._connection.cursor() as cursor:
            cursor.execute(f"SELECT count(*) FROM {_TABLE_NAME} WHERE corpus_key = %s", (corpus_key,))
            row = cursor.fetchone()
        return int(row[0]) if row is not None else 0

    def _distinct_rows(self, rows: list[tuple[str, str, str, float]], top_k: int) -> tuple[StoredChunk, ...]:
        selected: list[StoredChunk] = []
        seen_paths: set[str] = set()
        for source_path, title, content, score in rows:
            if source_path in seen_paths:
                continue
            seen_paths.add(source_path)
            selected.append(StoredChunk(source_path, title, content, float(score)))
            if len(selected) == top_k:
                break
        return tuple(selected)

    def _stored_rows(self, rows: list[tuple[str, str, str, float]], top_k: int) -> tuple[StoredChunk, ...]:
        return tuple(
            StoredChunk(source_path, title, content, float(score))
            for source_path, title, content, score in rows[:top_k]
        )

    def _distinct_keyword_rows(
        self,
        rows: list[tuple[str, str, str, float, float]],
        top_k: int,
    ) -> tuple[StoredChunk, ...]:
        selected: list[StoredChunk] = []
        seen_paths: set[str] = set()
        for source_path, title, content, _content_score, score in rows:
            if source_path in seen_paths:
                continue
            seen_paths.add(source_path)
            selected.append(StoredChunk(source_path, title, content, float(score)))
            if len(selected) == top_k:
                break
        return tuple(selected)

    def _keyword_rows(
        self,
        rows: list[tuple[str, str, str, float, float]],
        top_k: int,
    ) -> tuple[StoredChunk, ...]:
        return tuple(
            StoredChunk(source_path, title, content, float(score))
            for source_path, title, content, _content_score, score in rows[:top_k]
        )


def _expanded_terms(query: str) -> tuple[str, ...]:
    return tuple(
        dict.fromkeys(
            term
            for token in tokenize(query)
            for term in _TERM_ALIASES.get(token, (token,))
        )
    )


def _term_weight(term: str) -> int:
    """Prefer exact technical identifiers over generic Korean question words."""
    return 10 if len(term) >= 3 and term.isascii() and any(character.isalpha() for character in term) else 1
